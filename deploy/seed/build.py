#!/usr/bin/env python3
"""
Build sample data for the Quantum Education demo deployment from catalog.json.

  python3 build.py sql      -> writes sample-data.sql (media URLs use the {{MEDIA}} placeholder)
  python3 build.py media    -> renders thumbnails, avatars, narrated lesson videos and PDF handouts
                               into media/out/ (macOS: needs Google Chrome, `say`, and ffmpeg or Docker)

Object keys in media/out/ mirror the keys used in sample-data.sql, so uploading media/out/ to
<bucket>/seed/ makes every URL in the database resolve.
"""
import argparse
import html
import json
import os
import re
import shutil
import subprocess
import sys
import tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
CATALOG_PATH = os.path.join(HERE, "catalog.json")
SQL_OUT = os.path.join(HERE, "sample-data.sql")
MEDIA_OUT = os.path.join(HERE, "media", "out")

BRAND_DARK = "#00584B"
BRAND_LIGHT = "#C7EBE6"
BRAND_YELLOW = "#FFC300"


def load_catalog():
    with open(CATALOG_PATH, encoding="utf-8") as f:
        return json.load(f)


def slugify(text):
    return re.sub(r"[^a-z0-9]+", "-", text.lower()).strip("-")


def course_media_keys(course):
    """Deterministic object keys (relative to the seed/ prefix) for a course's media."""
    keys = {"thumbnail": "courses/%s.jpg" % course["slug"], "lessons": []}
    n = 0
    for module in course["modules"]:
        for lesson in module["lessons"]:
            n += 1
            ext = "mp4" if lesson["type"] == "VIDEO" else "pdf"
            keys["lessons"].append("lessons/%s/%02d-%s.%s" % (course["slug"], n, slugify(lesson["title"]), ext))
    return keys


def instructor_key(instructor_id):
    return "instructors/%s.jpg" % instructor_id


