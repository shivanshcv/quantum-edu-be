# ---------------------------------------------------------------------------

def q(value):
    """Quote a value as a MySQL literal."""
    if value is None:
        return "NULL"
    if isinstance(value, bool):
        return "1" if value else "0"
    if isinstance(value, (int, float)):
        return str(value)
    return "'" + str(value).replace("\\", "\\\\").replace("'", "''") + "'"


def money(value):
    return "NULL" if value is None else "%.2f" % value


def days_ago(n):
    return "DATE_SUB(NOW(6), INTERVAL %d DAY)" % n


def build_sql(catalog):
    out = []
    w = out.append
    w("-- GENERATED by deploy/seed/build.py from catalog.json. Do not edit by hand.")
    w("-- Sample catalogue, demo learners, orders and LMS progress for the Quantum Education demo.")
    w("-- {{MEDIA}} is replaced with <R2_PUBLIC_URL>/seed when the database is initialised.")
    w("SET NAMES utf8mb4;")
    w("SET time_zone = '+05:30';")
    w("START TRANSACTION;")
    w("")

    # Categories
    cat_ids = {}
    w("-- Categories")
    for i, cat in enumerate(catalog["categories"], start=1):
        cat_ids[cat["slug"]] = i
        w("INSERT INTO category (id, name, slug, parent_id, level, is_active) VALUES (%d, %s, %s, NULL, 0, 1);"
          % (i, q(cat["name"]), q(cat["slug"])))
    w("")

    instructors = catalog["instructors"]
    product_ids = {}
    content_ids = {}  # slug -> ordered list of (content_id, content_type)
    module_id = content_id = lesson_id = assessment_id = question_id = 0

    for pid, course in enumerate(catalog["courses"], start=1):
        product_ids[course["slug"]] = pid
        keys = course_media_keys(course)
        inst = instructors[course["instructor"]]
        attributes = {
            "badge": course.get("badge"),
            "highlights": course.get("highlights", []),
            "learningOutcomes": course.get("outcomes", []),
            "instructor": {
                "name": inst["name"],
                "role": inst["role"],
                "imageUrl": "{{MEDIA}}/" + instructor_key(course["instructor"]),
                "bio": inst["bio"],
                "credentials": inst["credentials"],
            },
            "certification": dict(course["certification"], icon="Award"),
            "outcomeHighlights": course.get("outcomeHighlights", []),
        }
        total_minutes = sum(l["minutes"] for m in course["modules"] for l in m["lessons"])
        first_video = next((k for k in keys["lessons"] if k.endswith(".mp4")), None)

        w("-- Product %d: %s" % (pid, course["title"]))
        w("INSERT INTO product (id, title, slug, short_description, long_description, price, discount_price, "
          "thumbnail_url, preview_video_url, difficulty_level, duration_minutes, is_published, is_featured, is_free, attributes) VALUES (")
        w("  %d, %s, %s,\n  %s,\n  %s,\n  %s, %s, %s, %s, %s, %d, %s, %s, %s,\n  %s);" % (
            pid, q(course["title"]), q(course["slug"]), q(course["short"]), q(course["long"]),
            money(course["price"]), money(course["discount"]),
            q("{{MEDIA}}/" + keys["thumbnail"]),
            q("{{MEDIA}}/" + first_video) if first_video else "NULL",
            q(course["level"]), total_minutes,
            q(course["published"]), q(course["featured"]), q(course["free"]),
            q(json.dumps(attributes, ensure_ascii=False)),
        ))
        for cat_slug in course["categories"]:
            w("INSERT INTO product_category (product_id, category_id) VALUES (%d, %d);" % (pid, cat_ids[cat_slug]))

        order_index = 0
        lesson_n = 0
        content_ids[course["slug"]] = []
        for m_index, module in enumerate(course["modules"]):
            module_id += 1
            w("INSERT INTO product_module (id, product_id, title, order_index) VALUES (%d, %d, %s, %d);"
              % (module_id, pid, q("Module %d: %s" % (m_index + 1, module["title"])), m_index))
            for lesson in module["lessons"]:
                content_id += 1
                lesson_id += 1
                key = keys["lessons"][lesson_n]
                lesson_n += 1
                w("INSERT INTO product_content (id, product_id, module_id, content_type, title, order_index, is_mandatory) "
                  "VALUES (%d, %d, %d, 'LESSON', %s, %d, 1);" % (content_id, pid, module_id, q(lesson["title"]), order_index))
                video = q("{{MEDIA}}/" + key) if lesson["type"] == "VIDEO" else "NULL"
                pdf = q("{{MEDIA}}/" + key) if lesson["type"] == "PDF" else "NULL"
                w("INSERT INTO lesson (id, product_content_id, lesson_type, video_url, pdf_url, ppt_url, duration_seconds) "
                  "VALUES (%d, %d, %s, %s, %s, NULL, %d);" % (lesson_id, content_id, q(lesson["type"]), video, pdf, lesson["minutes"] * 60))
                content_ids[course["slug"]].append((content_id, "LESSON"))
                order_index += 1
            quiz = module.get("quiz")
            if quiz:
                content_id += 1
                assessment_id += 1
                w("INSERT INTO product_content (id, product_id, module_id, content_type, title, order_index, is_mandatory) "
                  "VALUES (%d, %d, %d, 'ASSESSMENT', %s, %d, 1);"
                  % (content_id, pid, module_id, q("Module %d Assessment" % (m_index + 1)), order_index))
                w("INSERT INTO assessment (id, product_content_id, pass_percentage) VALUES (%d, %d, %d);"
                  % (assessment_id, content_id, quiz["pass"]))
                for question in quiz["questions"]:
                    question_id += 1
                    w("INSERT INTO assessment_question (id, assessment_id, question_text) VALUES (%d, %d, %s);"
                      % (question_id, assessment_id, q(question["q"])))
                    values = ", ".join("(%d, %s, %d)" % (question_id, q(opt), 1 if i == question["answer"] else 0)
                                       for i, opt in enumerate(question["options"]))
                    w("INSERT INTO assessment_option (question_id, option_text, is_correct) VALUES %s;" % values)
                content_ids[course["slug"]].append((content_id, "ASSESSMENT"))
                order_index += 1
        w("")

    # Demo users, orders, ownership, progress, cart
    demo = catalog["demo"]
    courses_by_slug = {c["slug"]: c for c in catalog["courses"]}
    order_id = 0
    w("-- Demo learners (password for all: %s)" % demo["password"])
    for uid, user in enumerate(demo["users"], start=1):
        w("INSERT INTO auth_user (id, email, password_hash, role, is_verified, created_at, last_login_at) "
          "VALUES (%d, %s, %s, 'USER', %s, %s, %s);" % (
              uid, q(user["email"]), q(demo["password_hash"]), q(user["verified"]),
              days_ago(user["joined_days_ago"]), days_ago(0) if user["verified"] else "NULL"))
        addr = user.get("address") or [None, None, None, None]
        full_name = "%s %s" % (user["first"], user["last"])
        w("INSERT INTO user_profile (user_id, first_name, last_name, billing_name, phone, address_line1, city, state, country, postal_code) "
          "VALUES (%d, %s, %s, %s, %s, %s, %s, %s, %s, %s);" % (
              uid, q(user["first"]), q(user["last"]), q(full_name if user.get("address") else None), q(user["phone"]),
              q(addr[0]), q(addr[1]), q(addr[2]), q("India" if user.get("address") else None), q(addr[3])))

        def insert_order(course_slug, status, days):
            course = courses_by_slug[course_slug]
            final = 0 if course["free"] else (course["discount"] if course["discount"] else course["price"])
            if course["free"]:
                pg_order, pg_payment = "'FREE'", "NULL"
            elif status == "SUCCESS":
                pg_order, pg_payment = q("order_demo%04d%02d" % (uid, product_ids[course_slug])), q("pay_demo%04d%02d" % (uid, product_ids[course_slug]))
            elif status == "FAILED":
                pg_order, pg_payment = q("order_demo%04d%02d" % (uid, product_ids[course_slug])), "NULL"
            else:
                pg_order, pg_payment = q("order_demo%04d%02d" % (uid, product_ids[course_slug])), "NULL"
            w("INSERT INTO orders (id, user_id, product_id, price, discount_price, final_price, gst_amount, billing_name, "
              "billing_address_line1, billing_city, billing_state, billing_country, billing_postal_code, "
              "payment_gateway_order_id, payment_gateway_payment_id, status, created_at, updated_at) VALUES "
              "(%d, %d, %d, %s, %s, %s, 0.00, %s, %s, %s, %s, 'India', %s, %s, %s, %s, %s, %s);" % (
                  order_id, uid, product_ids[course_slug], money(course["price"]), money(course["discount"]), money(final),
                  q(full_name), q(addr[0]), q(addr[1]), q(addr[2]), q(addr[3]),
                  pg_order, pg_payment, q(status), days_ago(days), days_ago(days)))

        for enrollment in user.get("enrollments", []):
            order_id += 1
            slug = enrollment["course"]
            insert_order(slug, "SUCCESS", enrollment["days_ago"])
            w("INSERT INTO course_ownership (user_id, course_id, order_id, purchased_at) VALUES (%d, %d, %d, %s);"
              % (uid, product_ids[slug], order_id, days_ago(enrollment["days_ago"])))
            items = content_ids[slug]
            done = len(items) if enrollment["progress"] == "all" else int(enrollment["progress"])
            for step, (cid, ctype) in enumerate(items[:done]):
                when = days_ago(max(enrollment["days_ago"] - step - 1, 0))
                if ctype == "ASSESSMENT":
                    w("INSERT INTO user_assessment_result (user_id, product_content_id, passed, score_percentage, created_at) "
                      "VALUES (%d, %d, 1, 100, %s);" % (uid, cid, when))
                w("INSERT INTO user_lesson_progress (user_id, product_content_id, completed_at, created_at) VALUES (%d, %d, %s, %s);"
                  % (uid, cid, when, when))
        for failed in user.get("failed_orders", []):
            order_id += 1
            insert_order(failed["course"], "FAILED", failed["days_ago"])
        for pending in user.get("pending_orders", []):
            order_id += 1
            insert_order(pending["course"], "PENDING", pending["days_ago"])
        for slug in user.get("cart", []):
            w("INSERT INTO cart (user_id, product_id) VALUES (%d, %d);" % (uid, product_ids[slug]))
        w("")

    w("COMMIT;")
    return "\n".join(out) + "\n"


