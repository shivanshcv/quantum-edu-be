class Renderer(object):
    def __init__(self, voice, tmp):
        self.tmp = tmp
        self.voice = voice
        self.chrome = os.environ.get("CHROME") or "/Applications/Google Chrome.app/Contents/MacOS/Google Chrome"
        if not os.path.exists(self.chrome):
            sys.exit("Google Chrome not found. Set CHROME=/path/to/chrome")
        for tool in ("say", "afinfo", "sips"):
            if not shutil.which(tool):
                sys.exit("`%s` not found: media generation requires macOS." % tool)
        self.ffmpeg_local = shutil.which("ffmpeg")
        if not self.ffmpeg_local and not shutil.which("docker"):
            sys.exit("Need ffmpeg (brew install ffmpeg) or Docker for video encoding.")

    def _write(self, name, content):
        path = os.path.join(self.tmp, name)
        with open(path, "w", encoding="utf-8") as f:
            f.write(content)
        return path

    def screenshot(self, html_text, out_jpg, width, height):
        src = self._write("page.html", html_text)
        png = os.path.join(self.tmp, "shot.png")
        subprocess.run([self.chrome, "--headless=new", "--disable-gpu", "--hide-scrollbars", "--force-device-scale-factor=1",
                        "--window-size=%d,%d" % (width, height), "--screenshot=%s" % png, "file://" + src],
                       check=True, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
        if out_jpg.endswith(".png"):
            shutil.copy(png, out_jpg)
        else:
            subprocess.run(["sips", "-s", "format", "jpeg", "-s", "formatOptions", "82", png, "--out", out_jpg],
                           check=True, stdout=subprocess.DEVNULL)

    def pdf(self, html_text, out_pdf):
        src = self._write("handout.html", html_text)
        subprocess.run([self.chrome, "--headless=new", "--disable-gpu", "--no-pdf-header-footer", "--print-to-pdf-no-header",
                        "--print-to-pdf=%s" % out_pdf, "file://" + src],
                       check=True, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)

    def speak(self, text, out_aiff):
        cmd = ["say", "-r", "170", "-o", out_aiff, text]
        if self.voice:
            cmd[1:1] = ["-v", self.voice]
        subprocess.run(cmd, check=True)
        info = subprocess.run(["afinfo", out_aiff], check=True, capture_output=True, text=True).stdout
        match = re.search(r"estimated duration:\s*([0-9.]+)", info)
        return float(match.group(1)) if match else 10.0

    def ffmpeg(self, args):
        if self.ffmpeg_local:
            subprocess.run([self.ffmpeg_local, "-hide_banner", "-loglevel", "error", "-y"] + args, check=True, cwd=self.tmp)
        else:
            subprocess.run(["docker", "run", "--rm", "-v", "%s:/w" % self.tmp, "-w", "/w", "linuxserver/ffmpeg:latest",
                            "-hide_banner", "-loglevel", "error", "-y"] + args, check=True,
                           stdout=subprocess.DEVNULL)

    def video(self, slides, out_mp4):
        """slides: list of (html, narration). Produces an H.264/AAC MP4 that plays in every browser."""
        segments = []
        for i, (slide_html, narration) in enumerate(slides):
            png, aiff, seg = "s%d.png" % i, "s%d.aiff" % i, "s%d.mp4" % i
            self.screenshot(slide_html, os.path.join(self.tmp, png), 1280, 720)
            duration = self.speak(narration, os.path.join(self.tmp, aiff)) + 1.0
            self.ffmpeg(["-loop", "1", "-framerate", "5", "-i", png, "-i", aiff,
                         "-t", "%.2f" % duration, "-af", "apad",
                         "-c:v", "libx264", "-preset", "medium", "-tune", "stillimage", "-pix_fmt", "yuv420p", "-r", "5",
                         "-c:a", "aac", "-b:a", "96k", "-ar", "44100", "-ac", "1", seg])
            segments.append(seg)
        self._write("list.txt", "".join("file '%s'\n" % s for s in segments))
        self.ffmpeg(["-f", "concat", "-safe", "0", "-i", "list.txt", "-c", "copy", "-movflags", "+faststart", "out.mp4"])
        shutil.move(os.path.join(self.tmp, "out.mp4"), out_mp4)


def build_media(catalog, voice, only):
    os.makedirs(MEDIA_OUT, exist_ok=True)
    tmp = tempfile.mkdtemp(prefix="qe-media-")
    r = Renderer(voice, tmp)

    def target(key):
        path = os.path.join(MEDIA_OUT, key)
        os.makedirs(os.path.dirname(path), exist_ok=True)
        return path

    def wanted(path):
        return only is None or only in path

    for inst_id, inst in catalog["instructors"].items():
        path = target(instructor_key(inst_id))
        if wanted(path) and not os.path.exists(path):
            print("avatar    ", path)
            r.screenshot(avatar_html(inst), path, 600, 600)

    for course in catalog["courses"]:
        keys = course_media_keys(course)
        path = target(keys["thumbnail"])
        if wanted(path) and not os.path.exists(path):
            print("thumbnail ", path)
            r.screenshot(thumbnail_html(catalog, course), path, 1280, 720)
        n = 0
        for m_index, module in enumerate(course["modules"]):
            for lesson in module["lessons"]:
                path = target(keys["lessons"][n])
                n += 1
                if not wanted(path) or os.path.exists(path):
                    continue
                print("%-10s" % lesson["type"].lower(), path)
                if lesson["type"] == "VIDEO":
                    intro = "%s. %s" % (lesson["title"], lesson["summary"])
                    body = "Here are the key points. " + " ".join(lesson["points"]) + \
                           " That wraps up this lesson. Mark it complete and continue to the next one."
                    r.video([(slide_title_html(course, module["title"], m_index + 1, lesson), intro),
                             (slide_points_html(lesson), body)], path)
                else:
                    r.pdf(handout_html(catalog, course, module["title"], m_index + 1, lesson), path)
    shutil.rmtree(tmp, ignore_errors=True)
    print("Media written to", MEDIA_OUT)


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = parser.add_subparsers(dest="cmd")
    sub.add_parser("sql", help="generate sample-data.sql")
    media = sub.add_parser("media", help="render demo media into media/out/")
    media.add_argument("--voice", default=os.environ.get("SAY_VOICE", "Rishi"), help="macOS `say` voice (default: Rishi)")
    media.add_argument("--only", help="only render files whose path contains this text")
    media.add_argument("--force", action="store_true", help="delete media/out/ first")
    args = parser.parse_args()

    catalog = load_catalog()
    if args.cmd == "sql":
        with open(SQL_OUT, "w", encoding="utf-8") as f:
            f.write(build_sql(catalog))
        print("Wrote", SQL_OUT)
    elif args.cmd == "media":
        if args.force and os.path.isdir(MEDIA_OUT):
            shutil.rmtree(MEDIA_OUT)
        voices = subprocess.run(["say", "-v", "?"], capture_output=True, text=True).stdout
        voice = args.voice if re.search(r"^%s\s" % re.escape(args.voice), voices, re.M) else None
        build_media(catalog, voice, args.only)
    else:
        parser.print_help()


if __name__ == "__main__":
    main()
